"""Build Dice Rolls' items.js: the names and grades of the items that can be
rolled for, from AION 2's own game data.

    python tools/dice-rolls/build_items.py --tables <...>/Output/AION2/Content/Data/Table

--tables is the Table folder the Aion2DataExtractor writes (Item.json and
L10N/<lang>/L10NString.json). The meter's roll events carry only an item id
(Item.ID); this gives each its name in the client's eight languages. Chinese
falls back to English until a Taiwan client's strings are added.

Kept: items that can change hands or bind on pickup (a roll hands one to a
player); account-bound items never drop to be rolled for.
"""
import argparse
import json
import os

LANG_DIRS = {"en": "en-US", "ko": "ko-KR", "ja": "ja-JP", "de": "de-DE", "fr": "fr-FR",
             "es": "es-ES", "pt": "pt-BR", "ru": "ru-RU"}
# The game's grades, lowest first: the plugin colours names by them.
GRADES = ["Common", "Rare", "Legend", "Unique", "Epic", "Special"]
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "plugins", "dice-rolls", "items.js")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tables", required=True)
    a = ap.parse_args()
    with open(os.path.join(a.tables, "Item.json"), encoding="utf-8") as f:
        items = json.load(f)["Properties"]["Data"]
    strings = {}
    for code, folder in LANG_DIRS.items():
        with open(os.path.join(a.tables, "L10N", folder, "L10NString.json"), encoding="utf-8") as f:
            strings[code] = json.load(f)["Entries"]

    out = {}
    for it in items:
        if it["ExchangeType"] == "EExchangeType::NonExchangeable":
            continue
        desc = it.get("Desc")
        key = desc.get("Key") if isinstance(desc, dict) else None
        keys = [f"String_{key}_body"] if key else []
        keys.append("String_STR_ITEM_" + it["Name"].upper() + "_body")
        key = next((k for k in keys if k in strings["en"]), None)
        if not key:
            continue
        en = strings["en"][key].strip()
        if not en or en in ("???", "None"):
            continue
        names = {"en": en}
        for code, entries in strings.items():
            t = (entries.get(key) or "").strip()
            if code != "en" and t and t not in ("???", "None") and t != en:
                names[code] = t
        grade = it["ItemGrade"].split("::")[-1]
        out[str(it["ID"]["Value"])] = [GRADES.index(grade) if grade in GRADES else 0, names]

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/dice-rolls/build_items.py from the game's Item table: each\n")
        f.write("// item id's grade (an index into DICE_GRADES) and name, English and the\n")
        f.write("// languages that differ from it.\n")
        f.write("globalThis.DICE_GRADES = " + json.dumps(GRADES) + ";\n")
        f.write("globalThis.DICE_ITEMS = ")
        json.dump(out, f, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
        f.write(";\n")
    print(f"{len(out)} items -> {os.path.normpath(OUT)} ({os.path.getsize(OUT) // 1024} KB)")


if __name__ == "__main__":
    main()
