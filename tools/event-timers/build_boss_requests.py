"""Build Event Timers' supply.js: which Boss supply requests each world boss
drops the gear for.

    python tools/event-timers/build_boss_requests.py --tables <...>/AION2/Content/Data/Table \
        --pool <A2-Tools>/assets/static/profiteer/recipes.json

From the client's tables (the same extract as build.py):
  WorldMapFieldNamed  each world boss (Event Timers' FIELD_BOSSES ids) and its
                      spawner; Map/**/MapData.json gives the spawner's NPC
  NpcLoot             each NPC's LootList (item ids)
and from Profiteer's request pool (recipes.json supply.pool, built from the
game's PeriodItemCollection): the Boss tab's requests (tab 4), each taking
any one of its target items. Every world boss's gear fills one request on
each side's Boss board (1014xxx Elyos, 2014xxx Asmodian), so a player can
tell which enemy boss drops what their own board asks for.
"""
import argparse
import json
import os
import sys
from collections import defaultdict

REPO = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
BOSS_TAB = 4


def v(x):
    return x["Value"] if isinstance(x, dict) else x


def load(t, name):
    with open(os.path.join(t, name), encoding="utf-8") as f:
        d = json.load(f)["Properties"]["Data"]
    return d if isinstance(d, list) else list(d.values())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tables", default=os.environ.get("A2_GAME_TABLES", ""))
    ap.add_argument("--pool", required=True, help="Profiteer's recipes.json (A2-Tools assets/static/profiteer)")
    ap.add_argument("--out", default=os.path.join(REPO, "plugins", "event-timers", "supply.js"))
    a = ap.parse_args()
    T = a.tables
    if not T or not os.path.isdir(T):
        sys.exit("--tables: the extracted Data/Table folder (or set A2_GAME_TABLES)")

    # Which NPC each spawner holds, from the maps' spawn data (as build.py).
    spawner_npc = {}
    for root, _, files in os.walk(os.path.join(os.path.dirname(os.path.normpath(T)), "Map")):
        if "MapData.json" in files:
            with open(os.path.join(root, "MapData.json"), encoding="utf-8") as f:
                md = json.load(f)["Properties"]["Data"]
            for sp in md["SpawnInfoList"]:
                if sp["NpcIdList"]:
                    spawner_npc[sp["Name"]] = v(sp["NpcIdList"][0])
    loot = {v(r["NpcId"]): {v(x) for x in r.get("LootList", [])} for r in load(T, "NpcLoot.json")}

    with open(a.pool, encoding="utf-8") as f:
        pool = json.load(f)["supply"]["pool"]
    pool = pool if isinstance(pool, list) else list(pool.values())
    takes = defaultdict(set)  # item id -> Boss-tab requests taking it
    for r in pool:
        if r.get("tab") == BOSS_TAB:
            for item in r["targets"]:
                takes[item].add(r["id"])

    out, missing = {}, []
    for r in load(T, "WorldMapFieldNamed.json"):
        if not r["SpawnType"].endswith("::Basic"):
            continue
        npc = spawner_npc.get(r["FieldNamedSpawnerName"])
        reqs = sorted(set().union(*(takes[i] for i in loot.get(npc, ()) if i in takes))) if npc else []
        if reqs:
            out[str(v(r["ID"]))] = reqs
        else:
            missing.append(str(v(r["ID"])))
    print(f"{len(out)} world bosses fill Boss requests; none found for {len(missing)}: {', '.join(sorted(missing))}",
          file=sys.stderr)

    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Which Boss supply requests each world boss drops the gear for, by\n")
        f.write("// world-map id (FIELD_BOSSES): one request on each side's Boss board.\n")
        f.write("// Generated by tools/event-timers/build_boss_requests.py: don't edit by hand.\n")
        f.write("const BOSS_REQUESTS = " + json.dumps(out, sort_keys=True) + ";\n")


if __name__ == "__main__":
    main()
